    public const string ResourcePrefix = "Loc.";

    public static string Language { get; private set; } = "en";

    public static event Action? Changed;

    public static void SetLanguage(string setting)
    {
        if (setting is "ru" or "en")
            Language = setting;
        else
        {
            var ui = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            Language = ui is "ru" or "uk" or "be" or "kk" ? "ru" : "en";
        }
        Changed?.Invoke();
    }

    public static string T(string key) =>
        Texts.TryGetValue(key, out var t) ? (Language == "ru" ? t.ru : t.en) : key;

    public static string T(string key, params object[] args) => string.Format(T(key), args);

